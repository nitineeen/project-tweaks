#!/usr/bin/env node
/**
 * Tweaks one-command setup.
 * Asks for the API base + key (or nothing for mock mode), writes
 * apps/web/.env.local, installs, verifies the gateway, creates the database.
 * Re-runnable. Needs Node 22+.
 *
 * Usage:  node setup.mjs [--yes]
 * Non-interactive (piped stdin or --yes): takes env or defaults —
 * SETUP_PORT, SETUP_BASE, SETUP_KEY, SETUP_SEARCH. Never overwrites an
 * existing .env.local unless asked interactively.
 */
import { createInterface } from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.join(ROOT, 'apps', 'web');
const ENV_PATH = path.join(WEB, '.env.local');

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, stdio: 'inherit', shell: process.platform === 'win32' });
  if (r.status !== 0) {
    console.error(`\nsetup stopped: "${cmd} ${args.join(' ')}" failed. Fix it and re-run node setup.mjs.`);
    process.exit(1);
  }
}

function tryInstall() {
  const r = spawnSync('npm', ['install'], { cwd: WEB, stdio: 'inherit', shell: process.platform === 'win32' });
  return r.status === 0;
}

function envFile({ port, base, key, search, token }) {
  const lines = [
    '# Generated by `node setup.mjs` — safe to re-run or edit by hand.',
    `AI_PROVIDER=${key ? 'real' : 'mock'}`,
    'DB_PROVIDER=sqlite',
    'AUTH_MODE=dev-token',
    'SQLITE_PATH=./.local/tweaks.db',
    `DEV_EXTENSION_TOKEN=${token}`,
    `NEXT_PUBLIC_WEB_URL=http://localhost:${port}`,
    `AI_API_BASE=${base}`,
    `AI_API_KEY=${key}`,
    'MODEL_CLASSIFY=muse-spark-1.3',
    'MODEL_VISION=muse-spark-1.3',
    'MODEL_SEGMENT=sam-3.1',
    'MODEL_RERANK=muse-spark-1.3',
    'MODEL_THINK=muse-spark-1.3',
    'MODEL_THINK_QUICK=muse-spark-1.1',
    'MODEL_THINK_DEEP=muse-spark-1.3',
    'MODEL_EMBED=open-weights-local',
    'MODEL_EMBED_DIMS=1024',
    'MODEL_IMAGE=muse-image-1.0',
    'MODEL_TRANSCRIBE=muse-voice-transcribe-1.0',
    '# MODEL_WONDER=muse-wonder-1.0',
    `SEARCH_API_KEY=${search}`,
    'MODEL_LOCAL=muse-spark-open',
    '',
  ];
  return lines.join('\n');
}

function patchPorts(port) {
  const pkgPath = path.join(WEB, 'package.json');
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
  for (const k of ['dev', 'start']) {
    if (pkg.scripts && pkg.scripts[k]) pkg.scripts[k] = pkg.scripts[k].replace(/-p \d+/, `-p ${port}`);
  }
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
  for (const f of ['src/popup.js', 'src/popup.html']) {
    const p = path.join(ROOT, 'apps', 'extension', f);
    if (!fs.existsSync(p)) continue;
    fs.writeFileSync(p, fs.readFileSync(p, 'utf8').replace(/http:\/\/localhost:\d+/g, `http://localhost:${port}`));
  }
}

async function checkGateway(base, key) {
  try {
    const res = await fetch(`${base.replace(/\/$/, '')}/models`, {
      headers: { Authorization: `Bearer ${key}` },
      signal: AbortSignal.timeout(15000),
    });
    if (!res.ok) {
      console.log(`! gateway answered http ${res.status} — key or base URL may be wrong. App still runs; fix .env.local later.`);
      return;
    }
    const data = await res.json().catch(() => ({}));
    const n = Array.isArray(data.data) ? data.data.length : Array.isArray(data) ? data.length : '?';
    console.log(`✓ gateway OK — ${n} models listed.`);
  } catch {
    console.log('! gateway unreachable — app still runs (mock fallback for failed calls). Check the key/base later.');
  }
}

const main = async () => {
  console.log('\n✳ tweaks setup\n');
  const major = Number(String(process.versions.node).split('.')[0]);
  if (!Number.isFinite(major) || major < 22) {
    console.error(`Node 22+ required (you have ${process.versions.node}). Install it, then re-run.`);
    process.exit(1);
  }
  if (!fs.existsSync(path.join(WEB, 'package.json'))) {
    console.error('Run this from the project root (apps/web/package.json not found).');
    process.exit(1);
  }
  // Batch mode: --yes flag or non-TTY stdin (pipes can't prompt reliably).
  const batch = process.argv.includes('--yes') || process.argv.includes('-y') || !input.isTTY;
  if (batch) console.log('(non-interactive: using env vars or defaults)\n');
  const rl = batch ? null : createInterface({ input, output });
  const ask = async (q, def, env) => {
    if (env && process.env[env] !== undefined && process.env[env] !== '') return process.env[env];
    if (batch) return def;
    const a = (await rl.question(def ? `${q} [${def}]: ` : `${q}: `)).trim();
    return a || def;
  };
  const port = (await ask('Port for the dashboard', '3121', 'SETUP_PORT')) || '3121';
  const base = (await ask('AI_API_BASE (Meta gateway)', 'https://api.meta.ai/v1', 'SETUP_BASE')) || 'https://api.meta.ai/v1';
  const key = await ask('AI_API_KEY (blank = mock mode, no key needed)', '', 'SETUP_KEY');
  const search = await ask('SEARCH_API_KEY, Brave (blank = skip live web search)', '', 'SETUP_SEARCH');
  let overwrite = 'y';
  if (fs.existsSync(ENV_PATH)) overwrite = batch ? 'n' : await ask('.env.local exists — overwrite? (y/N)', 'n');
  if (rl) rl.close();

  if (overwrite.toLowerCase().startsWith('y')) {
    const token = randomBytes(24).toString('hex');
    fs.writeFileSync(ENV_PATH, envFile({ port, base, key, search, token }));
    console.log('✓ wrote apps/web/.env.local');
  } else {
    console.log('· kept existing apps/web/.env.local');
  }
  patchPorts(port);
  console.log(`✓ dashboard port → ${port}`);

  console.log('\nInstalling (apps/web)…');
  if (!tryInstall()) {
    console.log("! this machine's npm cache is broken — retrying with a throwaway cache…");
    const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'tweaks-npm-'));
    run('npm', ['install', '--cache', tmp], WEB);
  }

  console.log('Creating the database…');
  run('node', ['-e', `import('./src/lib/db.js').then(m=>m.getDb()).then(()=>console.log('database ready'))`], WEB);

  if (key) await checkGateway(base, key);
  else console.log('· mock mode: no key, AI answers use built-in fixtures. Add a key later and restart.');

  const saved = fs.readFileSync(ENV_PATH, 'utf8').match(/DEV_EXTENSION_TOKEN=(\S+)/);
  const token = saved ? saved[1] : '(see apps/web/.env.local)';
  console.log(`
Done. Next:
  1. cd apps/web && npm run dev        →  http://localhost:${port}/think
  2. chrome://extensions → Developer mode → Load unpacked → apps/extension
  3. Extension popup → Connection → API URL http://localhost:${port} + token:
       ${token}
  4. Save any page (Alt+T), then ask about it in Think space.

Mock vs real: blank key = fixtures everywhere ("(mock read)" labels).
Paste a real key + AI_PROVIDER=real for live Meta models. See README.md.`);
};

main().catch((e) => {
  console.error(`\nsetup failed: ${String((e && e.message) || e).slice(0, 300)}`);
  process.exit(1);
});
